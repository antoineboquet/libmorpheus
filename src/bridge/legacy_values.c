uint32_t morpheus_public_degree(
    uint32_t legacy, morpheus_part_of_speech part_of_speech,
    const unsigned char *legacy_flags)
{
  if(legacy == COMPARATIVE || legacy_flag_is_set(legacy_flags,IRREG_COMP))
    return(MORPHEUS_DEGREE_COMPARATIVE);
  if(legacy == SUPERLATIVE || legacy_flag_is_set(legacy_flags,IRREG_SUPERL))
    return(MORPHEUS_DEGREE_SUPERLATIVE);
  if(part_of_speech == MORPHEUS_PART_OF_SPEECH_ADJECTIVE)
    return(MORPHEUS_DEGREE_POSITIVE);
  return(MORPHEUS_DEGREE_NONE);
}

