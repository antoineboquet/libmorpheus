void morpheus_public_morph_flags(
    uint8_t destination[MORPHEUS_MORPH_FLAG_CAPACITY],
    const unsigned char *legacy_flags)
{
  size_t i;
  memset(destination,0,MORPHEUS_MORPH_FLAG_CAPACITY);
  for(i=0;i<sizeof morph_flag_mappings/sizeof morph_flag_mappings[0];i++) {
    const morpheus_morph_flag index=morph_flag_mappings[i].public_index;
    if(legacy_flag_is_set(legacy_flags,morph_flag_mappings[i].legacy))
      destination[index/8u]|=(uint8_t)(UINT8_C(1)<<(index%8u));
  }
}

