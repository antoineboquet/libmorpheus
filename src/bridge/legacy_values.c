static int legacy_flag_is_set(const unsigned char *flags, int number)
{
  const size_t index=(size_t)(number-1)/8u;
  const unsigned int bit=(unsigned int)(number-1)%8u;
  return(index < MORPHFLAG_STORAGE_BYTES &&
         (flags[index] & (unsigned char)(UINT8_C(1)<<bit)) != 0);
}

#define MAP_BIT(legacy_bit,public_bit) \
  if((legacy & (uint32_t)(legacy_bit)) != 0) result|=(public_bit)

